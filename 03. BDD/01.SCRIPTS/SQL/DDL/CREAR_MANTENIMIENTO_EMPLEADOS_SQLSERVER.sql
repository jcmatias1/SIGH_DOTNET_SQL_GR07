/* Table: PEGEN_GENER (GENERO) */
IF OBJECT_ID('PEGEN_GENER', 'U') IS NULL
CREATE TABLE PEGEN_GENER
(
   PEGEN_CODIGO         CHAR(1) NOT NULL,
   PEGEN_DESCRI         VARCHAR(20) NOT NULL,
   CONSTRAINT PK_PEGEN_GENER PRIMARY KEY (PEGEN_CODIGO)
);
GO

/* Table: PEESC_ESTCI (ESTADO_CIVIL) */
IF OBJECT_ID('PEESC_ESTCI', 'U') IS NULL
CREATE TABLE PEESC_ESTCI
(
   PEESC_CODIGO         CHAR(1) NOT NULL,
   PEESC_DESCRI         VARCHAR(20) NOT NULL,
   CONSTRAINT PK_PEESC_ESTCI PRIMARY KEY (PEESC_CODIGO)
);
GO

MERGE PEGEN_GENER AS t
USING (VALUES ('M', 'Masculino'), ('F', 'Femenino')) AS s (PEGEN_CODIGO, PEGEN_DESCRI)
ON t.PEGEN_CODIGO = s.PEGEN_CODIGO
WHEN NOT MATCHED THEN INSERT (PEGEN_CODIGO, PEGEN_DESCRI) VALUES (s.PEGEN_CODIGO, s.PEGEN_DESCRI);
GO

MERGE PEESC_ESTCI AS t
USING (VALUES
 ('S', 'Soltero/a'),
 ('C', 'Casado/a'),
 ('D', 'Divorciado/a'),
 ('V', 'Viudo/a'),
 ('U', 'Unión de hecho')) AS s (PEESC_CODIGO, PEESC_DESCRI)
ON t.PEESC_CODIGO = s.PEESC_CODIGO
WHEN NOT MATCHED THEN INSERT (PEESC_CODIGO, PEESC_DESCRI) VALUES (s.PEESC_CODIGO, s.PEESC_DESCRI);
GO

/* Relaciones del modelo: GEN_EMP, ESC_EMP y CAR_EMP */
IF OBJECT_ID('FK_GEN_EMP', 'F') IS NULL
   ALTER TABLE PEEMP_EMPLE ADD CONSTRAINT FK_GEN_EMP FOREIGN KEY (PEGEN_CODIGO)
      REFERENCES PEGEN_GENER (PEGEN_CODIGO);
GO
IF OBJECT_ID('FK_ESC_EMP', 'F') IS NULL
   ALTER TABLE PEEMP_EMPLE ADD CONSTRAINT FK_ESC_EMP FOREIGN KEY (PEESC_CODIGO)
      REFERENCES PEESC_ESTCI (PEESC_CODIGO);
GO
IF OBJECT_ID('FK_CAR_EMP', 'F') IS NULL
   ALTER TABLE PEEMP_EMPLE ADD CONSTRAINT FK_CAR_EMP FOREIGN KEY (PEDEP_CODIGO, PECAR_CODIGO)
      REFERENCES PECAR_CARGO (PEDEP_CODIGO, PECAR_CODIGO);
GO

/* Opción del menú y permiso del perfil Administrador */
MERGE XEOPC_OPCIO AS t
USING (VALUES ('P003', 'PER', 'Mantenimiento de empleados', '/personal/empleados'))
      AS s (XEOPC_CODIGO, XESIS_CODIGO, XEOPC_DESCRI, XEOPC_URL)
ON t.XEOPC_CODIGO = s.XEOPC_CODIGO
WHEN MATCHED THEN UPDATE SET XESIS_CODIGO = s.XESIS_CODIGO, XEOPC_DESCRI = s.XEOPC_DESCRI, XEOPC_URL = s.XEOPC_URL
WHEN NOT MATCHED THEN INSERT (XEOPC_CODIGO, XESIS_CODIGO, XEOPC_DESCRI, XEOPC_URL)
     VALUES (s.XEOPC_CODIGO, s.XESIS_CODIGO, s.XEOPC_DESCRI, s.XEOPC_URL);
GO

MERGE XEOXP_OPCPE AS t
USING (VALUES ('ADM', 'P003')) AS s (XEPER_CODIGO, XEOPC_CODIGO)
ON t.XEPER_CODIGO = s.XEPER_CODIGO AND t.XEOPC_CODIGO = s.XEOPC_CODIGO
WHEN MATCHED THEN UPDATE SET XEOXP_FECRET = NULL
WHEN NOT MATCHED THEN INSERT (XEPER_CODIGO, XEOPC_CODIGO, XEOXP_FECASI, XEOXP_FECRET)
     VALUES (s.XEPER_CODIGO, s.XEOPC_CODIGO, GETDATE(), NULL);
GO

