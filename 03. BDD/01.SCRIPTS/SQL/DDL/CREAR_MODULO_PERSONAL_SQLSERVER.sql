/* Table: PEDEP_DEPAR (DEPARTAMENTO) */
IF OBJECT_ID('PEDEP_DEPAR', 'U') IS NULL
CREATE TABLE PEDEP_DEPAR
(
   PEDEP_CODIGO         CHAR(3) NOT NULL,
   PEDEP_DESCRI         VARCHAR(60) NOT NULL,
   CONSTRAINT PK_PEDEP_DEPAR PRIMARY KEY (PEDEP_CODIGO)
);
GO

/* Table: PECAR_CARGO (CARGO) */
IF OBJECT_ID('PECAR_CARGO', 'U') IS NULL
CREATE TABLE PECAR_CARGO
(
   PEDEP_CODIGO         CHAR(3) NOT NULL,
   PECAR_CODIGO         CHAR(3) NOT NULL,
   PECAR_DESCRI         VARCHAR(60) NOT NULL,
   CONSTRAINT PK_PECAR_CARGO PRIMARY KEY (PEDEP_CODIGO, PECAR_CODIGO),
   CONSTRAINT FK_DEP_CAR FOREIGN KEY (PEDEP_CODIGO)
      REFERENCES PEDEP_DEPAR (PEDEP_CODIGO)
);
GO

/* Departamentos base */
MERGE PEDEP_DEPAR AS t
USING (VALUES
 ('ADM', 'Administración'),
 ('CEX', 'Consulta externa'),
 ('EME', 'Emergencia'),
 ('HOS', 'Hospitalización'),
 ('LAB', 'Laboratorio'),
 ('IMA', 'Imagenología'),
 ('FAR', 'Farmacia'),
 ('QUI', 'Quirófano'),
 ('FAC', 'Facturación')) AS s (PEDEP_CODIGO, PEDEP_DESCRI)
ON t.PEDEP_CODIGO = s.PEDEP_CODIGO
WHEN NOT MATCHED THEN INSERT (PEDEP_CODIGO, PEDEP_DESCRI) VALUES (s.PEDEP_CODIGO, s.PEDEP_DESCRI);
GO

/* Cargos base */
MERGE PECAR_CARGO AS t
USING (VALUES
 ('ADM', 'ADS', 'Administrador de sistemas'),
 ('CEX', 'MED', 'Médico'),
 ('HOS', 'ENF', 'Enfermero/a'),
 ('FAR', 'FAR', 'Farmacéutico/a')) AS s (PEDEP_CODIGO, PECAR_CODIGO, PECAR_DESCRI)
ON t.PEDEP_CODIGO = s.PEDEP_CODIGO AND t.PECAR_CODIGO = s.PECAR_CODIGO
WHEN NOT MATCHED THEN INSERT (PEDEP_CODIGO, PECAR_CODIGO, PECAR_DESCRI) VALUES (s.PEDEP_CODIGO, s.PECAR_CODIGO, s.PECAR_DESCRI);
GO

/* Sistema PERSONAL (aparece en el menú arriba de SEGURIDAD) */
IF NOT EXISTS (SELECT 1 FROM XESIS_SISTE WHERE XESIS_CODIGO = 'PER')
   INSERT INTO XESIS_SISTE (XESIS_CODIGO, XESIS_DESCRI) VALUES ('PER', 'PERSONAL');
GO

/* Opciones del menú: si ya existen se corrigen su descripción y URL */
MERGE XEOPC_OPCIO AS t
USING (VALUES
 ('P001', 'PER', 'Administrar departamentos', '/personal/departamentos'),
 ('P002', 'PER', 'Administrar cargos',        '/personal/cargos')) AS s (XEOPC_CODIGO, XESIS_CODIGO, XEOPC_DESCRI, XEOPC_URL)
ON t.XEOPC_CODIGO = s.XEOPC_CODIGO
WHEN MATCHED THEN UPDATE SET XESIS_CODIGO = s.XESIS_CODIGO, XEOPC_DESCRI = s.XEOPC_DESCRI, XEOPC_URL = s.XEOPC_URL
WHEN NOT MATCHED THEN INSERT (XEOPC_CODIGO, XESIS_CODIGO, XEOPC_DESCRI, XEOPC_URL)
     VALUES (s.XEOPC_CODIGO, s.XESIS_CODIGO, s.XEOPC_DESCRI, s.XEOPC_URL);
GO

/* Permisos del perfil Administrador */
MERGE XEOXP_OPCPE AS t
USING (VALUES ('ADM', 'P001'), ('ADM', 'P002')) AS s (XEPER_CODIGO, XEOPC_CODIGO)
ON t.XEPER_CODIGO = s.XEPER_CODIGO AND t.XEOPC_CODIGO = s.XEOPC_CODIGO
WHEN MATCHED THEN UPDATE SET XEOXP_FECRET = NULL
WHEN NOT MATCHED THEN INSERT (XEPER_CODIGO, XEOPC_CODIGO, XEOXP_FECASI, XEOXP_FECRET)
     VALUES (s.XEPER_CODIGO, s.XEOPC_CODIGO, GETDATE(), NULL);
GO

/* Verificación */
SELECT * FROM PEDEP_DEPAR ORDER BY PEDEP_DESCRI;
SELECT c.PEDEP_CODIGO, d.PEDEP_DESCRI, c.PECAR_CODIGO, c.PECAR_DESCRI
  FROM PECAR_CARGO c JOIN PEDEP_DEPAR d ON d.PEDEP_CODIGO = c.PEDEP_CODIGO
 ORDER BY d.PEDEP_DESCRI, c.PECAR_DESCRI;
SELECT * FROM XEOPC_OPCIO WHERE XESIS_CODIGO = 'PER';
SELECT * FROM XEOXP_OPCPE WHERE XEOPC_CODIGO IN ('P001', 'P002');
GO
